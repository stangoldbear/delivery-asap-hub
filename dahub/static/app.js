  /* A new link row copies its class and placeholder from the rows the server
     already rendered, so field names and placeholders stay defined in one
     place (dahub/settings.toml) instead of being restated here. */
  function buildLinkRow(container, pid, kind) {
    var template = container.querySelector('.link-row input');
    var row = document.createElement('div');
    row.className = 'link-row';

    var input = document.createElement('input');
    input.type = 'text';
    input.className = template ? template.className : 'form-input form-input--grow';
    input.placeholder = template ? template.placeholder : '';
    input.value = '';
    input.dataset.change = 'project-field';
    input.dataset.project = pid;

    var remove = document.createElement('button');
    remove.type = 'button';
    remove.className = 'del-btn';
    remove.textContent = '✕';
    remove.dataset.action = 'link-remove';
    remove.dataset.project = pid;
    remove.dataset.kind = kind;

    row.append(input, remove);
    return row;
  }

  /* ─── Single event-delegation router ────────────────────────────────────── */
  document.addEventListener('click', function (event) {
    var target = event.target.closest('[data-action]');
    if (!target || target.disabled) return;

    var handler = ClickActions[target.dataset.action];
    if (!handler) {
      Toast.error('Unregistered action: ' + target.dataset.action);
      return;
    }
    event.preventDefault();
    handler(target, target.dataset, event);
  });

  document.addEventListener('change', function (event) {
    var target = event.target.closest('[data-change]');
    if (!target) return;
    var handler = ChangeActions[target.dataset.change];
    if (handler) handler(target, target.dataset);
  });

  /* ─── Sticky column resize ──────────────────────────────────────────────────
     The whole layout hangs off the `--label-w` custom property emitted by the
     server, so dragging only has to update that one variable: the column, the
     sticky cells, the table width and the "today" band all follow from CSS. */
  var ColumnResize = {
    width: function () { return cssNumber('--label-w', 340); },

    apply: function (width) {
      var min = cssNumber('--label-w-min', 160);
      var max = cssNumber('--label-w-max', 900);
      var clamped = Math.max(min, Math.min(max, Math.round(width)));
      document.documentElement.style.setProperty('--label-w', clamped + 'px');
      return clamped;
    },

    save: function (width) {
      try { localStorage.setItem(LABEL_W_KEY, String(width)); } catch (err) { /* noop */ }
    },

    /* The drag handle spans the chart, whose height only the browser knows. */
    syncHeight: function () {
      var table = byId('gantt-table');
      if (table) {
        document.documentElement.style.setProperty('--chart-h', table.offsetHeight + 'px');
      }
    },

    restore: function () {
      var saved = null;
      try { saved = parseFloat(localStorage.getItem(LABEL_W_KEY)); } catch (err) { saved = null; }
      if (saved && !isNaN(saved)) this.apply(saved);
    },

    init: function () {
      var bar = document.querySelector('.col-resize-handle__bar');
      var self = this;
      if (!bar) return;

      var dragging = false;
      var startX = 0;
      var startWidth = 0;

      bar.addEventListener('mousedown', function (event) {
        dragging = true;
        startX = event.clientX;
        startWidth = self.width();
        bar.classList.add('is-dragging');
        document.body.classList.add('col-resize-active');
        event.preventDefault();
      });

      document.addEventListener('mousemove', function (event) {
        if (!dragging) return;
        self.apply(startWidth + (event.clientX - startX));
      });

      function endDrag() {
        if (!dragging) return;
        dragging = false;
        bar.classList.remove('is-dragging');
        document.body.classList.remove('col-resize-active');
        self.save(self.width());
      }

      document.addEventListener('mouseup', endDrag);
      document.addEventListener('mouseleave', endDrag);

      this.syncHeight();
      var table = byId('gantt-table');
      if (table && window.ResizeObserver) {
        new ResizeObserver(function () { self.syncHeight(); }).observe(table);
      } else {
        window.addEventListener('resize', function () { self.syncHeight(); });
      }
    }
  };

  /* ─── Drag & drop reordering ────────────────────────────────────────────── */
  var DragAndDrop = {
    init: function () {
      var draggedRow = null;
      var tbody = document.querySelector('.gantt-table tbody');
      if (!tbody) return;

      function clearMarkers() {
        all('.drag-over-top, .drag-over-bottom').forEach(function (el) {
          el.classList.remove('drag-over-top', 'drag-over-bottom');
        });
      }

      function targetRow(el) {
        var tr = el.closest ? el.closest('tr') : null;
        if (!tr) return null;
        if (tr.classList.contains('project-main-row') || tr.classList.contains('tier-row')) {
          return tr;
        }
        var previous = tr.previousElementSibling;
        while (previous) {
          if (previous.classList.contains('project-main-row')) return previous;
          previous = previous.previousElementSibling;
        }
        return null;
      }

      tbody.addEventListener('dragstart', function (event) {
        var row = event.target.closest('.project-main-row');
        if (!row) return;
        draggedRow = row;
        event.dataTransfer.effectAllowed = 'move';
        event.dataTransfer.setData('text/plain', row.dataset.projId || '');
        row.classList.add('is-dragging');
      });

      tbody.addEventListener('dragend', function () {
        if (draggedRow) draggedRow.classList.remove('is-dragging');
        draggedRow = null;
        clearMarkers();
      });

      tbody.addEventListener('dragover', function (event) {
        event.preventDefault();
        var row = targetRow(event.target);
        if (!row || row === draggedRow) return;

        clearMarkers();
        if (row.classList.contains('tier-row')) {
          row.classList.add('drag-over-bottom');
          row.dataset.dropPos = 'after';
        } else {
          var rect = row.getBoundingClientRect();
          var bottomHalf = (event.clientY - rect.top) > (rect.height / 2);
          row.classList.add(bottomHalf ? 'drag-over-bottom' : 'drag-over-top');
          row.dataset.dropPos = bottomHalf ? 'after' : 'before';
        }
        event.dataTransfer.dropEffect = 'move';
      });

      tbody.addEventListener('dragleave', function (event) {
        var row = targetRow(event.target);
        if (row) row.classList.remove('drag-over-top', 'drag-over-bottom');
      });

      tbody.addEventListener('drop', function (event) {
        event.preventDefault();
        clearMarkers();

        var target = targetRow(event.target);
        if (!target || !draggedRow || target === draggedRow) return;

        var dropPos = target.dataset.dropPos || 'before';
        var moved = draggedRow.dataset.projId;
        var currentTier = null;
        var order = [];

        all('.gantt-table tbody > tr').forEach(function (row) {
          if (row.classList.contains('tier-row')) {
            currentTier = row.dataset.tier;
            if (row === target) order.push({ id: moved, tier: currentTier });
            return;
          }
          if (!row.classList.contains('project-main-row')) return;

          if (row === target && dropPos === 'before') order.push({ id: moved, tier: currentTier });
          if (row !== draggedRow) order.push({ id: row.dataset.projId, tier: currentTier });
          if (row === target && dropPos === 'after') order.push({ id: moved, tier: currentTier });
        });

        reloadOnSuccess(post('/api/project/_batch/reorder', { order: order }));
      });
    }
  };

  document.addEventListener('DOMContentLoaded', function () {
    UIState.restore();
    ColumnResize.init();
    ColumnResize.restore();
    DragAndDrop.init();
  });
